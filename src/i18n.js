// translate one interface string; {name} placeholders are filled from vars
function t(lang, s, vars) {
  let r = (UI[lang] && UI[lang][s]) || s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return r;
}
// the strings the browser needs (shell, loader, car module), served as /assets/i18n-<lang>.js
function clientDict(lang) { return UI[lang] || {}; }

// "3 Series" -> "Seria 3", "5-door" -> "5 uși" (model names come from the dataset in English)
function seriesName(name, lang) {
  if (lang !== 'ro' || !name) return name;
  return name.replace(/\b(\d) Series\b/g, 'Seria $1').replace(/\b(\d)-door\b/g, '$1 uși');
}
const num = (n, lang) => Number(n).toLocaleString(LOCALE[lang] || 'en-GB');

// ---------- data translations ----------
const DATA = {};
for (const l of LANGS) {
  if (l === DEFAULT) continue;
  const f = path.join(__dirname, `torque-data.${l}.json`);
  try { DATA[l] = JSON.parse(fs.readFileSync(f, 'utf8')); } catch { DATA[l] = {}; }
}
// translated text of one dataset string, or null when there is no translation (the English stays)
function td(lang, s) {
  if (!s || lang === DEFAULT) return null;
  const d = DATA[lang];
  const r = d && d[s];
  return r && r !== s ? r : null;
}
const dataCount = (lang) => Object.keys(DATA[lang] || {}).length;

module.exports = { LANGS, DEFAULT, LOCALE, OG_LOCALE, prefix, t, clientDict, seriesName, num, td, dataCount };
